const COMPLAINT_STATUS = Object.freeze({
  SUBMITTED: 'SUBMITTED',
  UNDER_REVIEW: 'UNDER_REVIEW',
  ASSIGNED: 'ASSIGNED',
  IN_PROGRESS: 'IN_PROGRESS',
  RESOLVED: 'RESOLVED',
  CLOSED: 'CLOSED',
  REJECTED: 'REJECTED',
  DUPLICATE: 'DUPLICATE',
  CANCELLED: 'CANCELLED',
});

const ALL_COMPLAINT_STATUSES = Object.values(COMPLAINT_STATUS);

/**
 * Valid state transitions mapping
 * key: current status, value: array of allowed next statuses
 */
const VALID_STATUS_TRANSITIONS = Object.freeze({
  [COMPLAINT_STATUS.SUBMITTED]: [
    COMPLAINT_STATUS.UNDER_REVIEW,
    COMPLAINT_STATUS.CANCELLED,
    COMPLAINT_STATUS.REJECTED,
  ],
  [COMPLAINT_STATUS.UNDER_REVIEW]: [
    COMPLAINT_STATUS.ASSIGNED,
    COMPLAINT_STATUS.REJECTED,
    COMPLAINT_STATUS.DUPLICATE,
    COMPLAINT_STATUS.CANCELLED,
  ],
  [COMPLAINT_STATUS.ASSIGNED]: [
    COMPLAINT_STATUS.IN_PROGRESS,
    COMPLAINT_STATUS.REJECTED,
    COMPLAINT_STATUS.CANCELLED,
  ],
  [COMPLAINT_STATUS.IN_PROGRESS]: [
    COMPLAINT_STATUS.RESOLVED,
    COMPLAINT_STATUS.ASSIGNED, // Reassignment
  ],
  [COMPLAINT_STATUS.RESOLVED]: [
    COMPLAINT_STATUS.CLOSED,
    COMPLAINT_STATUS.IN_PROGRESS, // Reopened if not satisfied
  ],
  [COMPLAINT_STATUS.CLOSED]: [],
  [COMPLAINT_STATUS.REJECTED]: [],
  [COMPLAINT_STATUS.DUPLICATE]: [],
  [COMPLAINT_STATUS.CANCELLED]: [],
});

